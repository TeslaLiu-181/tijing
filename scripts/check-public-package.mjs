function safeRelative(path){
 return typeof path==='string'&&path.length>0&&!/[\\\0\r\n]/.test(path)&&!path.startsWith('/')&&!/^[A-Za-z]:/.test(path)&&!path.split('/').some(part=>!part||part==='.'||part==='..');
}
function location(path){
 if(!safeRelative(path)){fail('invalid_relative_path',String(path));return null;}
 const full=resolve(root,path),rel=relative(root,full);
 if(isAbsolute(rel)||rel==='..'||rel.startsWith('..\\')||rel.startsWith('../')){fail('path_outside_package',path);return null;}
 return full;
}
function forbidden(path){
 const parts=path.split('/'),name=parts.at(-1);
 return parts.some(part=>excludedDirectories.has(part)||/^(?:backups?|logs?)$/i.test(part))
  ||((name==='.env'||name.startsWith('.env.')||name.endsWith('.env'))&&name!=='.env.example')
  ||/^id_(?:rsa|dsa|ecdsa|ed25519)$/i.test(name)
  ||/\.(?:pem|key|pfx|p12|keystore|sqlite3?|db)(?:-(?:wal|shm))?$/i.test(name)
  ||/\.(?:bak|backup|old|orig|log|bundle|zip|7z|tar|tgz|gz|br)$/i.test(name)
  ||knownGeneratedHTML.has(path);
}
