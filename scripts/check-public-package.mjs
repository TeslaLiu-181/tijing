   checkEqual(entry.originalSourceSHA256,guide.sha256,'guide_source_hash_mismatch',assetPath);
   checkEqual(entry.paragraphCount,guide.paragraphs?.length,'guide_paragraph_count_mismatch',assetPath);
   checkEqual(entry.embeddedImageCount,Object.keys(guide.images??{}).length,'guide_image_count_mismatch',assetPath);
