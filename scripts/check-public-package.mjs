function fixtureValue(path,value){
 if(fixtureDigests.get(path)?.has(sha(value)))return true;
 const fixtureFile=path.startsWith('tests/')||/^scripts\/(?:check-|qa-|ai-)/.test(path);
 return fixtureFile&&/synthetic|fixture|fake|example|dummy|placeholder|never[-_ ]?(?:transmit|use)|not[-_ ]?transmit/i.test(value);
}
function placeholder(value){
 return /^(?:<[^>]+>|(?:YOUR|CHANGE_ME|REPLACE_ME|EXAMPLE|PLACEHOLDER)(?:[_ -].*)?)$/i.test(value);
}
function scanSecrets(path,text){
 // Embedded teaching images/font bytes are binary assets, not credential text.
 const plain=text.replace(/data:[^,\s"']+;base64,[A-Za-z0-9+/=\r\n]+/g,match=>match.replace(/[^\r\n]/g,' '));
 const strong=/-----BEGIN (?:RSA |EC |DSA |OPENSSH |ENCRYPTED )?PRIVATE KEY-----|\b(?:sk-(?:proj-)?[A-Za-z0-9_-]{16,}|AIza[0-9A-Za-z_-]{30,}|AKIA[0-9A-Z]{16}|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{30,}|xox[baprs]-[A-Za-z0-9-]{20,})\b/g;
 for(const match of plain.matchAll(strong)){
  if(!fixtureValue(path,match[0])&&!placeholder(match[0]))fail('possible_secret',path,lineAt(plain,match.index));
 }
 const assignment=/(?<![\w-])(?:[A-Z][A-Z0-9_]*(?:API_KEY|PASSWORD|APP_SECRET|CLIENT_SECRET|ACCESS_TOKEN|REFRESH_TOKEN)|api[_-]?key|app[_-]?secret|client[_-]?secret|(?:access|refresh)[_-]?token|(?:admin|teacher|student)?[_-]?password)\b["']?\s*[:=]\s*(["'])([^"'\r\n]{8,})\1/gi;
 for(const match of plain.matchAll(assignment)){
  if(!fixtureValue(path,match[2])&&!placeholder(match[2])&&!match[2].includes('$'+'{'))fail('possible_secret_literal',path,lineAt(plain,match.index));
 }
}
